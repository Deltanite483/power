import assert from 'node:assert/strict';
import { createServer } from 'vite';
import * as THREE from 'three';
const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' });
try {
  const { LaserVision } = await server.ssrLoadModule('/src/laser-vision.ts');
  const { Faora } = await server.ssrLoadModule('/src/faora.ts');
  const scene = new THREE.Scene(); let clear = true;
  const fighter = { availableToFight: true, bodyScale: 1, pos: new THREE.Vector3(), model: new THREE.Group(), eyePosition: (index, out) => out.set(index ? .048 : -.048, 1.737, .134), lineClear: () => clear, firstBlock: () => clear ? 1 : 0 };
  const player = { pos: new THREE.Vector3(0, 0, 25), eyeLevel: 1.6, vitals: { defeated: false } };
  const laser = new LaserVision(scene); let hits = 0, charges = 0, fires = 0;
  laser.onHit = () => hits++; laser.onCharge = () => charges++; laser.onFire = () => fires++;
  for (let i = 0; i < 100; i++) laser.update(.05, fighter, player, true);
  assert.equal(charges, 1); assert.equal(fires, 1); assert.ok(hits > 0, 'clear beam damages target');
  const before = hits; fighter.availableToFight = false;
  for (let i = 0; i < 200; i++) laser.update(.05, fighter, player, true);
  assert.equal(hits, before, 'passive fighter cannot fire');
  fighter.availableToFight = true; clear = false;
  for (let i = 0; i < 200; i++) laser.update(.05, fighter, player, true);
  assert.equal(hits, before, 'wall prevents firing');
  clear = true;
  const dodge = new LaserVision(scene); let dodgedHits = 0;
  dodge.onHit = () => dodgedHits++;
  let fired = false; dodge.onFire = () => fired = true;
  for (let i = 0; i < 100 && !fired; i++) dodge.update(.05, fighter, player, true);
  const initialHits = dodgedHits; player.pos.x = 8;
  for (let i = 0; i < 20; i++) dodge.update(.05, fighter, player, true);
  assert.equal(dodgedHits, initialHits, 'moving aside dodges locked beam');
  // A missed beam carries on and burns whatever it lands on.
  player.pos.set(0, 0, 25); let burns = 0;
  const burner = new LaserVision(scene); let burnerFired = false;
  burner.onFire = () => burnerFired = true; burner.onBurn = () => (burns++, 1);
  fighter.firstBlock = () => .6;
  for (let i = 0; i < 100 && !burnerFired; i++) burner.update(.05, fighter, player, true);
  player.pos.x = 8;
  for (let i = 0; i < 10; i++) burner.update(.05, fighter, player, true);
  assert.ok(burns > 0, 'blocked beam burns terrain');
  fighter.firstBlock = () => clear ? 1 : 0;
  const distant = new LaserVision(scene); let distantHits = 0;
  player.pos.set(0, 0, 240);
  distant.onHit = () => distantHits++;
  for (let i = 0; i < 100; i++) distant.update(.05, fighter, player, true);
  assert.ok(distantHits > 0, 'heat vision reaches a distant opponent');

  const held = new LaserVision(scene); let grabHits = 0;
  player.pos.set(0, 0, 2);
  fighter.availableToFight = false;
  held.onHit = (_strength, target) => { assert.equal(target, player); grabHits++; };
  for (let i = 0; i < 30; i++) held.update(.05, fighter, player, true, true);
  assert.ok(grabHits > 0, 'heat vision can hit the holder at point-blank range');
  const beforeRelease = grabHits;
  for (let i = 0; i < 30; i++) held.update(.05, fighter, player, true);
  assert.equal(grabHits, beforeRelease, 'grab counter ends when the holder lets go');
  const spans = { top: 0, floor: () => 0, ceil: () => Infinity, solid: () => false };
  const passive = new Faora({ spans: () => spans }, new THREE.Scene());
  passive.passive = true;
  passive.strike(new THREE.Vector3(1, 0, 0), new THREE.Vector3(), 1, true, 1);
  assert.equal(passive.hostile, false, 'Friend assignment stays passive when struck');
  console.log('Laser: telegraph, damage, passive state, obstruction, dodging, long range and grab counter passed.');
} finally { await server.close(); }
