import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createServer} from 'vite';
const server=await createServer({server:{middlewareMode:true,hmr:false},appType:'custom'});
try {
  globalThis.addEventListener=()=>{};globalThis.document={addEventListener(){},pointerLockElement:null};
  const {Player}=await server.ssrLoadModule('/src/player.ts');
  const {MomentumWaves,momentumPower,momentumContact}=await server.ssrLoadModule('/src/momentum.ts');
  const player=new Player({},{});player.setFlying(true);player.receiveHit(100);
  assert.equal(player.flying,false,'heavy hit disables flight');
  player.vitals.orientation=0;player.vel.set(150,-220,-75);player.pounding=true;player.charging=true;player.jumpCharge=1;
  const position=player.pos.clone(),hp=player.vitals.health,velocity=player.vel.clone();
  const released=player.cancelMomentum();
  assert(released.equals(velocity),'snapshots all axes of inherited knockback');
  assert.equal(player.vel.length(),0);assert.equal(player.flying,true,'Q overrides hit-disabled flight even at zero orientation');
  assert.equal(player.pounding,false);assert.equal(player.charging,false);assert.equal(player.jumpCharge,0);
  assert(player.pos.equals(position),'no teleport');assert.equal(player.vitals.health,hp,'no free heal');assert.equal(player.vitals.orientation,0,'no free orientation reset');
  player.vitals.health=0;player.vel.set(4,5,6);assert.equal(player.cancelMomentum(),null,'defeat cannot be escaped with Q');assert.equal(player.vel.lengthSq(),77);
  const slow=momentumPower(10),fast=momentumPower(400),extreme=momentumPower(3000);
  for(const field of ['range','radius','impulse','strength'])assert(slow[field]<fast[field] && fast[field]<extreme[field],field+' scales with kinetic energy');
  for(const speed of [0,-1,NaN,Infinity,1e300])for(const value of Object.values(momentumPower(speed)))assert(Number.isFinite(value),'power stays bounded');
  const waves=new MomentumWaves(new THREE.Scene());
  assert.equal(waves.spawn(new THREE.Vector3(),new THREE.Vector3()),null,'standing still cannot generate free attacks');
  const wave=waves.spawn(new THREE.Vector3(),new THREE.Vector3(0,0,-400));
  assert(wave.direction.equals(new THREE.Vector3(0,0,-1)),'points along velocity');
  assert(momentumContact(wave,new THREE.Vector3(0,0,-50),1,0,60)>0,'swept front catches a target during a large step');
  assert.equal(momentumContact(wave,new THREE.Vector3(0,0,5),1,0,60),0,'never hits behind the source');
  assert.equal(momentumContact(wave,new THREE.Vector3(30,0,-50),1,0,60),0,'does not hit outside cone');
  assert.equal(momentumContact(wave,new THREE.Vector3(0,0,-50),1,60,80),0,'past front cannot re-hit');
  const falling=waves.spawn(new THREE.Vector3(0,100,0),new THREE.Vector3(0,-300,0));
  assert(momentumContact(falling,new THREE.Vector3(0,60,0),1,0,50)>0,'falling arrest releases downward');
  assert.equal(momentumContact(falling,new THREE.Vector3(0,110,0),1,0,50),0);
  const victim={}, source={name:'Anissa',team:'foe',action:'shockwave'};
  const ram=waves.spawn(new THREE.Vector3(8,0,0),new THREE.Vector3(240,0,0),source,[victim]);
  assert.equal(ram.source,source,'ram splash keeps the attacker attribution');
  assert(ram.hit.has(victim),'the direct victim is excluded from the impact shockwave');
  for(let i=0;i<40;i++)waves.spawn(new THREE.Vector3(),new THREE.Vector3(100,0,0));
  assert.equal(waves.waves.length,8,'fixed active pressure budget');assert.equal(waves.rings.group.children.length,24,'fixed visual mesh budget');
  for(let i=0;i<120;i++)waves.update(1/60);
  assert.equal(waves.waves.length,0);assert(waves.rings.group.children.every(mesh=>!mesh.visible),'all effects expire');
  console.log('Momentum cancel: hit-disabled flight, zero-orientation recovery, full stop, direction, energy scaling, swept cone, defeat guard and effect budgets passed.');
}finally{await server.close();}
