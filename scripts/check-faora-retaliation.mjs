import assert from "node:assert/strict";
import { createServer } from "vite";
import * as THREE from "three";

const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: "custom" });
try {
  const { Faora } = await server.ssrLoadModule("/src/faora.ts");
  const spans = { top: 0, water: false, floor: () => 0, ceil: () => Infinity, solid: () => false };
  const world = { spans: () => spans, materialAt: () => ({ bounce: 0 }), crater() {}, launch() {} };
  const friend = new Faora(world, new THREE.Scene());
  const player = { pos: new THREE.Vector3(3, 0, 0), vel: new THREE.Vector3(), speed: 0, yaw: 0, pitch: 0, flying: false, onGround: true, inWater: false, combatAttacking: false };
  let hits = 0; const charges = [], styles = [], hitRanges = [];
  friend.onCounterAttack = (_direction, charge, style) => { hits++; charges.push(charge); styles.push(style); hitRanges.push(friend.pos.distanceTo(player.pos)); return true; };
  friend.strike(new THREE.Vector3(1, 0, 0), new THREE.Vector3(), 5, true);
  assert.equal(friend.hostile, true, "a player's hit provokes her");
  friend.ragdoll.stop(); friend.pos.set(0, 0, 0); friend.vel.set(0, 0, 0);
  friend.recall(player);
  friend.update(.05, player);
  assert.equal(friend.state, "retaliate", "recall cannot cancel retaliation");
  for (let i = 0; i < 180 && hits < 2; i++) friend.update(.05, player);
  assert.equal(hits, 2, "Faora retaliates twice");
  assert.ok(charges[0] >= .2 && charges[0] < .3 && charges[1] >= .85, "Faora charges a quick punch and a stronger smash");
  assert.deepEqual(styles, ["straight", "uppercut"], "grounded combat uses straight punches and uppercuts");
  assert.ok(hitRanges.every(range => range >= 1.5 && range <= 6), "fighter maintains punching distance");
  assert.equal(friend.state, "follow");
  assert.equal(friend.hostile, false, "two landed hits settle the score");
  friend.strike(new THREE.Vector3(1, 0, 0), new THREE.Vector3(), 5, true);
  friend.ragdoll.stop(); friend.pos.set(0, 0, 0); friend.vel.set(0, 0, 0);
  friend.onCounterAttack = () => false;
  friend.angerTime = .1;
  friend.update(.05, player); friend.update(.05, player);
  assert.equal(friend.state, "follow", "anger expires without a landed hit");
  friend.strike(new THREE.Vector3(1, 0, 0), new THREE.Vector3(), 5);
  assert.equal(friend.hostile, false, "incidental impacts do not provoke her");
  const guard = new Faora(world, new THREE.Scene());
  guard.pos.set(0, 0, 0);
  player.pos.set(20, 0, 0); player.yaw = Math.PI / 2; player.combatAttacking = true; player.combatAttackCharge = .3;
  for (let i = 0; i < 20; i++) { guard.pos.set(0, 0, 0); guard.vel.set(0, 0, 0); guard.update(.05, player); }
  assert.ok(guard.blocking && guard.defense.guard > 20, "Faora raises a guard against a visible wind-up");
  for (let i = 0; i < 20; i++) { guard.pos.set(0, 0, 0); guard.vel.set(0, 0, 0); guard.update(.05, player); }
  assert.equal(guard.blocking, false, "a charge held on her too long makes her drop the guard and move");
  guard.defense.begin("guard"); guard.defense.guard = 100;
  const before = guard.vel.clone();
  assert.equal(guard.strike(new THREE.Vector3(1, 0, 0), new THREE.Vector3(), 100, true, 60), false);
  assert.ok(guard.vel.equals(before) && !guard.ragdoll.active, "a full guard prevents knockback");
  assert.ok(Math.abs(guard.defense.guard - 40) < .001, "blocking consumes attack strength");
  assert.equal(guard.strike(new THREE.Vector3(1, 0, 0), new THREE.Vector3(), 100, true, 100), true);
  assert.ok(guard.ragdoll.active && guard.vel.x > 0 && guard.vel.x < 5, `partial guard and resistance scale knockback: ${guard.vel.x}`);
  player.combatAttackCharge = 0;
  const enemy = new Faora(world, new THREE.Scene(), "Anissa");
  player.pos.set(3, 0, 0); player.combatAttacking = false;
  enemy.pos.set(0, 0, 0); enemy.setEnemyMode(true);
  let enemyHits = 0; enemy.onCounterAttack = () => { enemyHits++; return true; };
  for (let i = 0; i < 200; i++) enemy.update(.05, player);
  assert.ok(enemyHits >= 2 && enemy.state === "retaliate", "enemy mode remains hostile after hits");
  player.onGround = false;
  enemy.pos.set(0, 0, 0); enemy.vel.set(0, 0, 0); enemy.counterCooldown = 0;
  let airborneStyle = null;
  enemy.onCounterAttack = (_direction, _charge, style) => { airborneStyle = style; return true; };
  for (let i = 0; i < 100 && airborneStyle === null; i++) enemy.update(.05, player);
  assert.equal(airborneStyle, "down", "airborne targets are punched toward the ground");
  enemy.setEnemyMode(false);
  assert.equal(enemy.state, "follow", "turning enemy mode off restores friendly behavior");
  const pursuer = new Faora(world, new THREE.Scene(), "Anissa");
  player.pos.set(35, 0, 0); player.vel.set(10, 0, 0); player.speed = 10; player.onGround = true;
  pursuer.pos.set(0, 0, 0); pursuer.setEnemyMode(true);
  pursuer.onCounterAttack = () => false;
  for (let i = 0; i < 160; i++) { player.pos.addScaledVector(player.vel, .05); pursuer.update(.05, player); }
  const separation = pursuer.pos.distanceTo(player.pos);
  assert.ok(separation > 1.2 && separation < 8, `moving target pursuit should settle at striking range, got ${separation}`);
  const dodger = new Faora(world, new THREE.Scene());
  player.pos.set(20, 0, 0); player.vel.set(0, 0, 0); player.speed = 0; player.yaw = Math.PI / 2;
  player.combatAttacking = true; player.combatAttackCharge = .8;
  dodger.pos.set(0, 0, 0); dodger.setEnemyMode(true);
  // She needs a frame to see you and a 0.4 s reaction before she moves.
  for (let i = 0; i < 12; i++) dodger.update(.05, player);
  assert.ok(dodger.dodgeTime > 0 && !dodger.blocking, "a heavy aimed wind-up triggers a dodge rather than simultaneous guard");
  const breaker = new Faora(world, new THREE.Scene(), "Anissa");
  player.pos.set(3, 0, 0); player.combatAttacking = false; player.combatGuard = 80; player.combatWhiff = 0;
  breaker.pos.set(0, 0, 0); breaker.setEnemyMode(true);
  let guardBreakCharge = 0;
  breaker.onCounterAttack = (_direction, charge) => { guardBreakCharge = charge; return false; };
  for (let i = 0; i < 100 && guardBreakCharge === 0; i++) breaker.update(.05, player);
  assert.ok(guardBreakCharge >= .95, "a strong guard draws a heavy attack");
  const punisher = new Faora(world, new THREE.Scene());
  player.combatGuard = 0; player.combatWhiff = 1;
  punisher.pos.set(0, 0, 0); punisher.setEnemyMode(true);
  let punishCharge = 0;
  punisher.onCounterAttack = (_direction, charge) => { punishCharge = charge; return false; };
  for (let i = 0; i < 100 && punishCharge === 0; i++) punisher.update(.05, player);
  assert.ok(punishCharge >= .2 && punishCharge < .3, "a miss invites a quick punish");
  const roofed = { top: 30, floor: () => 0, ceil: () => 3, solid: y => y < 0 || (y >= 3 && y < 30) };
  const recoveryWorld = { ...world, spans: () => roofed };
  const trapped = new Faora(recoveryWorld, new THREE.Scene(), "Anissa");
  trapped.setEnemyMode(true); trapped.pos.set(0, -5, 0);
  assert.equal(trapped.recoverFromTerrain(.4), false, "brief penetration does not teleport");
  assert.equal(trapped.recoverFromTerrain(.4), true, "sustained burial is recovered");
  assert.equal(trapped.pos.y, 55, "fighter respawns in clear sky above the terrain");
  assert.equal(trapped.state, "retaliate", "recovery preserves enemy mode");
  trapped.pos.set(0, 0, 0);
  assert.equal(trapped.recoverFromTerrain(2), false, "a clear room under a roof is not treated as burial");
  trapped.pos.set(0, -5, 0); trapped.held = true;
  assert.equal(trapped.recoverFromTerrain(2), false, "a held fighter is not teleported away");
  console.log("Faora: player provocation, chase, counterattacks, calm-down and timeout passed.");
} finally { await server.close(); }
